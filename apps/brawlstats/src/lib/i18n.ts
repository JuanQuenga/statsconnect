export type TranslationKey = BaseTranslationKey | FeatureTranslationKey;
export type Translator = (
  key: TranslationKey,
  values?: TranslationValues,
) => string;

const en: Record<TranslationKey, string> = {
  ...baseEnglish,
  ...featureEnglish,
};
const es: Record<TranslationKey, string> = { ...esBase, ...esFeature };
const de: Record<TranslationKey, string> = { ...deBase, ...deFeature };
const fr: Record<TranslationKey, string> = { ...frBase, ...frFeature };
const pt: Record<TranslationKey, string> = { ...ptBase, ...ptFeature };
const ja: Record<TranslationKey, string> = { ...jaBase, ...jaFeature };
const ko: Record<TranslationKey, string> = { ...koBase, ...koFeature };

const translations: Record<Locale, Record<TranslationKey, string>> = {
  en,
  es,
  de,
  fr,
  pt,
  ja,
  ko,
};
export const localeLabels: Record<Locale, string> = {
  en: "English",
  es: "Español",
  de: "Deutsch",
  fr: "Français",
  pt: "Português",
  ja: "日本語",
  ko: "한국어",
};

function interpolate(template: string, values?: TranslationValues): string {
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    values[key] === undefined ? match : String(values[key]),
  );
}

export function useI18n() {
  const { locale } = usePreferences();
  const t = useCallback<Translator>(
    (key, values) => interpolate(translations[locale][key], values),
    [locale],
  );
  const number = useCallback(
    (value: number, options?: Intl.NumberFormatOptions) =>
      new Intl.NumberFormat(locale, options).format(value),
    [locale],
  );
  const date = useCallback(
    (value: number | Date, options?: Intl.DateTimeFormatOptions) =>
      new Intl.DateTimeFormat(locale, options).format(value),
    [locale],
  );
  return {
    locale,
    t,
    number,
    date,
  };
}
